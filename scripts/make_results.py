"""Generate RESULTS.md and results/metrics.json from the raw arm
records. Verdicts are computed here from the pass lines frozen in
PREREGISTRATION.md, never typed by hand. With incomplete runs the
generated RESULTS.md says so and shows no verdicts."""
import json
import statistics
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

import common  # noqa: E402


def _load_jsonl(path):
    records = {}
    if Path(path).exists():
        for line in open(path, encoding="utf-8"):
            line = line.strip()
            if line:
                rec = json.loads(line)
                records[rec["doc"]] = rec
    return records


def _spread(times):
    if not times:
        return {"median": None, "mean": None, "iqr": None}
    q = statistics.quantiles(times, n=4, method="inclusive")
    return {
        "median": statistics.median(times),
        "mean": statistics.fmean(times),
        "iqr": q[2] - q[0],
    }


def verdicts(m):
    """Frozen pass lines from PREREGISTRATION.md."""
    out = {}
    diff = m["arm_b"]["f1"] - m["arm_a"]["f1"]
    out["H1"] = ("CONFIRMED" if diff >= 0.15
                 else "REFUTED" if diff <= 0.00 else "INCONCLUSIVE")
    wer = m["arm_a"]["wer"]
    out["H2"] = ("CONFIRMED" if wer >= 0.10
                 else "REFUTED" if wer < 0.05 else "INCONCLUSIVE")
    ta = m["arm_a"]["time"]["median"]
    tb = m["arm_b"]["time"]["median"]
    out["H3"] = ("CONFIRMED" if 5 * ta <= tb
                 else "REFUTED" if ta >= tb else "INCONCLUSIVE")
    return out


def compute(data_dir="data", results_dir="results"):
    doc_ids = common.test_doc_ids(data_dir)
    arm_a = _load_jsonl(Path(results_dir) / "arm_a.jsonl")
    arm_b = _load_jsonl(Path(results_dir) / "arm_b.jsonl")
    metrics = {"documents_expected": len(doc_ids),
               "arm_a_documents": len(arm_a),
               "arm_b_documents": len(arm_b)}
    if len(arm_a) != len(doc_ids) or len(arm_b) != len(doc_ids):
        return metrics, None

    rows = []
    tp_a = pred_a = tp_b = pred_b = truth = 0
    edits = ref_tokens = 0
    times_a, times_b = [], []
    b_calls = b_failures = 0
    for doc_id in doc_ids:
        ann = common.load_annotation(common.annotation_path(data_dir, doc_id))
        gt = common.ground_truth_pairs(ann)
        ra, rb = arm_a[doc_id], arm_b[doc_id]
        ta, pa, na = common.match_pairs([tuple(p) for p in ra["pairs"]], gt)
        tb, pb, nb = common.match_pairs([tuple(p) for p in rb["pairs"]], gt)
        _, _, f1a = common.prf(ta, pa, na)
        _, _, f1b = common.prf(tb, pb, nb)
        tp_a += ta; pred_a += pa; tp_b += tb; pred_b += pb; truth += na
        edits += ra["wer_edits"]; ref_tokens += ra["ref_tokens"]
        times_a.append(ra["seconds"]); times_b.append(rb["seconds"])
        b_calls += rb["calls"]; b_failures += 1 if rb["failed"] else 0
        rows.append({
            "doc": doc_id, "truth": na,
            "a_pred": pa, "a_tp": ta, "a_f1": f1a, "a_seconds": ra["seconds"],
            "a_wer": (ra["wer_edits"] / ra["ref_tokens"]) if ra["ref_tokens"] else 0.0,
            "b_pred": pb, "b_tp": tb, "b_f1": f1b, "b_seconds": rb["seconds"],
            "b_failed": rb["failed"],
        })
    pa_, ra_, f1a_ = common.prf(tp_a, pred_a, truth)
    pb_, rb_, f1b_ = common.prf(tp_b, pred_b, truth)
    metrics.update({
        "arm_a": {"tp": tp_a, "predicted": pred_a, "truth": truth,
                  "precision": pa_, "recall": ra_, "f1": f1a_,
                  "wer": edits / ref_tokens if ref_tokens else 0.0,
                  "wer_edits": edits, "ref_tokens": ref_tokens,
                  "time": _spread(times_a)},
        "arm_b": {"tp": tp_b, "predicted": pred_b, "truth": truth,
                  "precision": pb_, "recall": rb_, "f1": f1b_,
                  "calls": b_calls, "failures": b_failures,
                  "time": _spread(times_b)},
        "rows": rows,
    })
    metrics["verdicts"] = verdicts(metrics)
    return metrics, rows


def _fmt(x, digits=4):
    return ("%%.%df" % digits) % x


def render(metrics):
    lines = ["# Results", ""]
    if "verdicts" not in metrics:
        lines += [
            "Status: AWAITING RUNS. Arm A records: %d of %d documents. "
            "Arm B records: %d of %d documents. No verdicts exist yet; "
            "this file is generated by scripts/make_results.py and "
            "cannot be mistaken for results."
            % (metrics["arm_a_documents"], metrics["documents_expected"],
               metrics["arm_b_documents"], metrics["documents_expected"]),
            "",
        ]
        return "\n".join(lines)
    a, b, v = metrics["arm_a"], metrics["arm_b"], metrics["verdicts"]
    lines += [
        "Generated by scripts/make_results.py from results/arm_a.jsonl "
        "and results/arm_b.jsonl. Verdicts are computed from the pass "
        "lines frozen in PREREGISTRATION.md.",
        "",
        "## Headline numbers",
        "",
        "| Measure | Arm A: Tesseract + rules | Arm B: Gemini vision |",
        "| --- | --- | --- |",
        "| Field precision (micro) | %s | %s |" % (_fmt(a["precision"]), _fmt(b["precision"])),
        "| Field recall (micro) | %s | %s |" % (_fmt(a["recall"]), _fmt(b["recall"])),
        "| Field F1 (micro) | %s | %s |" % (_fmt(a["f1"]), _fmt(b["f1"])),
        "| True positives / predicted / ground truth | %d / %d / %d | %d / %d / %d |"
        % (a["tp"], a["predicted"], a["truth"], b["tp"], b["predicted"], b["truth"]),
        "| Median seconds per document | %s | %s |" % (_fmt(a["time"]["median"], 3), _fmt(b["time"]["median"], 3)),
        "| Mean seconds per document | %s | %s |" % (_fmt(a["time"]["mean"], 3), _fmt(b["time"]["mean"], 3)),
        "| Time IQR (seconds) | %s | %s |" % (_fmt(a["time"]["iqr"], 3), _fmt(b["time"]["iqr"], 3)),
        "",
        "Arm A OCR word error rate (micro): %s (%d edits over %d reference tokens)."
        % (_fmt(a["wer"]), a["wer_edits"], a["ref_tokens"]),
        "",
        "Arm B: %d API calls for %d documents; %d failed documents "
        "(counted, with zero predicted pairs, never dropped)."
        % (b["calls"], metrics["documents_expected"], b["failures"]),
        "",
        "## Verdicts",
        "",
        "- H1 (vision-LLM beats classical on field F1 by at least 0.15): "
        "**%s**. F1 difference is %s."
        % (v["H1"], _fmt(b["f1"] - a["f1"])),
        "- H2 (classical OCR WER is at least 0.10): **%s**. Measured WER is %s."
        % (v["H2"], _fmt(a["wer"])),
        "- H3 (classical arm at least 5 times faster per document): "
        "**%s**. Median times: Arm A %s s, Arm B %s s (ratio %s)."
        % (v["H3"], _fmt(a["time"]["median"], 3), _fmt(b["time"]["median"], 3),
           _fmt(b["time"]["median"] / a["time"]["median"], 2) if a["time"]["median"] else "n/a"),
        "",
        "## Per-document table",
        "",
        "| Document | GT pairs | A pred | A TP | A F1 | A WER | A s | B pred | B TP | B F1 | B s | B failed |",
        "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |",
    ]
    for r in metrics["rows"]:
        lines.append(
            "| %s | %d | %d | %d | %s | %s | %s | %d | %d | %s | %s | %s |"
            % (r["doc"], r["truth"], r["a_pred"], r["a_tp"], _fmt(r["a_f1"], 3),
               _fmt(r["a_wer"], 3), _fmt(r["a_seconds"], 2), r["b_pred"],
               r["b_tp"], _fmt(r["b_f1"], 3), _fmt(r["b_seconds"], 2),
               "yes" if r["b_failed"] else "no"))
    lines.append("")
    return "\n".join(lines)


def main():
    metrics, _rows = compute(str(ROOT / "data"), str(ROOT / "results"))
    (ROOT / "RESULTS.md").write_text(render(metrics), encoding="utf-8")
    serializable = {k: v for k, v in metrics.items() if k != "rows"}
    serializable["rows"] = metrics.get("rows", [])
    (ROOT / "results" / "metrics.json").write_text(
        json.dumps(serializable, indent=2) + "\n", encoding="utf-8")
    print("verdicts:", metrics.get("verdicts", "none yet"))


if __name__ == "__main__":
    main()
